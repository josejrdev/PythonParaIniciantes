# Algoritmo que calcula o dobro e o triplo de um número

# Coleta o numero 
numero = int(input("Digite um número: "))

# Calcula o dobro do número coletado
dobro = numero * 2

# Calcula o triplo do número coletado
triplo = numero * 3

# Exibe o resultado
print(str(dobro) + " é o dobro do número " + str(numero) + ". " + str(triplo) + " é o triplo.")